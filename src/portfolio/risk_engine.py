"""
Production Risk Engine and Execution Safety Layer.

=============================================================================
CRITICAL ARCHITECTURAL DESIGN PRINCIPLE: THE SUPREMACY OF RISK
-----------------------------------------------------------------------------
The Risk Engine sits independent of and strictly ABOVE any model, strategy, or
order-generation pipeline.

1. Hard Architectural Rule (Non-Bypassable Gate):
   - Every single order intent generated by any strategy (directional ML, pairs
     trading, mean-reversion, or manual override) MUST pass through and be
     evaluated by the Risk Engine before reaching the execution layer / broker.
   - The Risk Engine has absolute authority to BLOCK or RESIZE any order.
   - Strategy and ML signals NEVER override Risk Engine decisions. If a model
     predicts a 99% win probability with 5x leverage, but the portfolio is in a
     drawdown halt, the order is categorically BLOCKED.

2. Defense-in-Depth Safety Rules:
   - Maximum Drawdown Kill Switch:
     Halt all new position openings if running portfolio drawdown exceeds the
     limit (e.g. 15-20%). Only de-risking and position-closing trades are approved.
   - Daily Loss Limit (Prop-Desk Circuit Breaker):
     Halt trading for the remainder of the session if intra-day losses
     (realized + unrealized) breach a hard threshold (e.g. 3-5%).
   - Position and Exposure Limits:
     Enforce single-asset caps (respecting Phase 35 Kelly caps), aggregate
     gross leverage caps, net market exposure ceilings, and sector concentration.
   - Dynamic Volatility-Based De-risking:
     Directly connected to Phase 14 GARCH volatility forecasting. When conditional
     volatility spikes above historical norms, position sizes are automatically
     and proportionally hair-cutted.

3. Full Auditability:
   - Every intervention (blocked orders, size reductions, triggered circuit
     breakers) is recorded with complete context (timestamp, ticker, rule triggered,
     original size vs approved size, rationale) for audit trails (Phase 47).
=============================================================================
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date, datetime
from enum import Enum
from typing import Any, Callable, Sequence

import pandas as pd

from src.utils.logger import get_logger

logger = get_logger(__name__)


