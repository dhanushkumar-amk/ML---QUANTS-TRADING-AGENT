# 1. Enums and Data Containers
# ============================================================


class OrderAction(str, Enum):
    """Trading action direction."""

    BUY = "BUY"
    SELL = "SELL"


class DecisionStatus(str, Enum):
    """Risk engine evaluation outcome."""

    APPROVED = "APPROVED"
    RESIZED = "RESIZED"
    BLOCKED = "BLOCKED"


class RiskRule(str, Enum):
    """Specific safety rule triggering intervention."""

    NONE = "NONE"
    DRAWDOWN_KILL_SWITCH = "DRAWDOWN_KILL_SWITCH"
    DAILY_LOSS_LIMIT = "DAILY_LOSS_LIMIT"
    POSITION_LIMIT = "POSITION_LIMIT"
    GROSS_EXPOSURE_LIMIT = "GROSS_EXPOSURE_LIMIT"
    NET_EXPOSURE_LIMIT = "NET_EXPOSURE_LIMIT"
    SECTOR_CONCENTRATION_LIMIT = "SECTOR_CONCENTRATION_LIMIT"
    VOLATILITY_DERISKING = "VOLATILITY_DERISKING"


@dataclass
class RiskConfig:
    """Configuration parameters for portfolio risk rules."""

    max_drawdown_pct: float = 0.15  # 15% drawdown halts new risk
    daily_loss_limit_pct: float = 0.03  # 3% daily loss circuit breaker
    max_position_size_pct: float = 0.25  # 25% single-asset Kelly cap
    max_gross_exposure: float = 1.0  # 100% maximum gross leverage
    max_net_exposure: float = 1.0  # 100% maximum net market exposure
    max_sector_concentration: float = 0.40  # 40% maximum per sector
    vol_spike_threshold: float = 1.50  # GARCH vol > 1.5x baseline triggers de-risking
    min_vol_derisk_multiplier: float = 0.20  # Minimum position scale floor under extreme vol
    sector_mappings: dict[str, str] = field(
        default_factory=lambda: {
            "AAPL": "Technology",
            "MSFT": "Technology",
            "NVDA": "Technology",
            "GOOGL": "Communication",
            "AMZN": "ConsumerDiscretionary",
            "TSLA": "ConsumerDiscretionary",
            "SPY": "BroadMarket",
            "QQQ": "BroadTech",
            "XLK": "Technology",
        }
    )


@dataclass
class PortfolioState:
    """Current dynamic state of the investment portfolio."""

    current_equity: float
    peak_equity: float
    daily_start_equity: float
    current_date: str | date | datetime
    positions: dict[str, float] = field(default_factory=dict)  # ticker -> current market value
    realized_pnl_today: float = 0.0
    unrealized_pnl_today: float = 0.0

    @property
    def current_drawdown(self) -> float:
        """Current drawdown from peak equity as a positive fraction."""
        if self.peak_equity <= 0.0:
            return 0.0
        dd = (self.peak_equity - self.current_equity) / self.peak_equity
        return max(0.0, float(dd))

    @property
    def daily_loss_pct(self) -> float:
        """Total intra-day loss as a positive fraction of daily start equity."""
        if self.daily_start_equity <= 0.0:
            return 0.0
        total_pnl = self.realized_pnl_today + self.unrealized_pnl_today
        if total_pnl >= 0:
            return 0.0
        return float(abs(total_pnl) / self.daily_start_equity)

    @property
    def gross_exposure_value(self) -> float:
        """Total dollar value of all open long and short positions."""
        return float(sum(abs(val) for val in self.positions.values()))

    @property
    def gross_exposure_pct(self) -> float:
        """Gross exposure as a fraction of current equity."""
        if self.current_equity <= 0.0:
            return 0.0
        return float(self.gross_exposure_value / self.current_equity)

    @property
    def net_exposure_value(self) -> float:
        """Net dollar exposure (longs minus shorts)."""
        return float(sum(self.positions.values()))

    @property
    def net_exposure_pct(self) -> float:
        """Net exposure as a fraction of current equity."""
        if self.current_equity <= 0.0:
            return 0.0
        return float(abs(self.net_exposure_value) / self.current_equity)


@dataclass
class OrderIntent:
    """Order intent generated by a model or strategy requiring risk clearance."""

    ticker: str
    action: OrderAction | str
    quantity: float
    price: float
    order_type: str = "MARKET"
    timestamp: str | datetime | None = None
    is_closing: bool = False  # If True, order closes or reduces existing exposure
    metadata: dict[str, Any] = field(default_factory=dict)

    @property
    def dollar_value(self) -> float:
        """Estimated total dollar value of the order."""
        return float(abs(self.quantity * self.price))


@dataclass
class OrderDecision:
    """Final decision rendered by the risk engine for an order intent."""

    status: DecisionStatus
    intent: OrderIntent
    approved_quantity: float
    approved_dollar_value: float
    rule_triggered: RiskRule = RiskRule.NONE
    reasons: list[str] = field(default_factory=list)
    timestamp: str | datetime | None = None

    def to_audit_dict(self) -> dict[str, Any]:
        """Convert decision to structured dictionary for audit logging."""
        return {
            "timestamp": str(self.timestamp) if self.timestamp else str(datetime.now()),
            "ticker": self.intent.ticker,
            "action": _normalize_action(self.intent.action),
            "status": str(self.status.value),
            "rule_triggered": str(self.rule_triggered.value),
            "requested_quantity": round(float(self.intent.quantity), 4),
            "approved_quantity": round(float(self.approved_quantity), 4),
            "requested_value": round(float(self.intent.dollar_value), 2),
            "approved_value": round(float(self.approved_dollar_value), 2),
            "reasons": "; ".join(self.reasons) if self.reasons else "Within risk parameters",
        }


