                "Crucially, $\\text{Corr}(r_t, r_{t-k}) = 0$ does **not** mean $r_t$ and $r_{t-k}$ are independent. Independence requires $f(r_t, r_{t-k}) = f(r_t) f(r_{t-k})$. In market data, the second moment (variance/volatility) displays massive serial correlation:\n",
                "$$\\text{Corr}(r_t^2, r_{t-k}^2) > 0 \\quad \\text{and} \\quad \\text{Corr}(|r_t|, |r_{t-k}|) > 0$$\n",
