                "## 1. Theoretical Foundations: Why Volatility Clusters\n",
                "\n",
                "### 1.1 The Absence of Linear Autocorrelation\n",
                "Under the weak-form Efficient Market Hypothesis (EMH), future price movements cannot be linearly predicted from past prices:\n",
                "$$\\text{Corr}(r_t, r_{t-k}) \\approx 0 \\quad \\forall k \\ge 1$$\n",
